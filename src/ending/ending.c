static void EndingLookAt(MATRIX* m, SVECTOR* eye, SVECTOR* target, VECTOR* up) {
    VECTOR d;
    VECTOR x;
    VECTOR y;
    VECTOR z;

    d.vx = target->vx - eye->vx;
    d.vy = target->vy - eye->vy;
    d.vz = target->vz - eye->vz;
    VectorNormal(&d, &z);

    if (z.vz == up->vz) {
        z.vz++;
    }

    gte_ldopv1(&z);
    gte_ldopv2(up);
    gte_op12();
    gte_stlvnl(&d);
    VectorNormal(&d, &x);

    gte_ldopv1(&z);
    gte_ldopv2(&x);
    gte_op12();
    gte_stlvnl(&d);
    VectorNormal(&d, &y);

    m->m[0][0] = x.vx;
    m->m[0][1] = x.vy;
    m->m[0][2] = x.vz;
    m->m[1][0] = y.vx;
    m->m[1][1] = y.vy;
    m->m[1][2] = y.vz;
    m->m[2][0] = z.vx;
    m->m[2][1] = z.vy;
    m->m[2][2] = z.vz;

    gte_SetRotMatrix(m);
    gte_ldv0(eye);
    gte_rtv0();
    gte_stlvnl(m->t);
    m->t[0] = -m->t[0];
    m->t[1] = -m->t[1];
    m->t[2] = -m->t[2];
}

