static const char cd_msg_err[] = "scea file read error\n";
void ENDING_SceaLoop(void) {
    RECT rect;
    CdlFILE file;
    s32 buf;
    s32 r;
    s32 g;
    s32 b;
    s32 i;
    s32 res;
    s32 ode;
    s32 tp;
    u8* src;

    SetGameResolution(640, 480, 0x200, 0, 0, 0);

    do {
        res = (s32)CdSearchFile(&file, "\\STARTUP\\SCEAP.LZS;1");
        if (res <= 0) {
            if (res >= -1) {
                printf(cd_msg_err);
                return;
            }
        }

        CdControlB(CdlSetloc, (u_char*)&file, NULL);
        CdRead((file.size + 0x7FF) >> 11, (void*)0x80180000, 0x80);

        do {
            res = CdReadSync(1, 0);
        } while (res > 0);
    } while (res != 0);

    SystemLzsDecompress((u8*)0x80180000, (u8*)0x80100000);
    SetDispMask(1);

    b = 0xFE;
    g = 0xFE;
    r = 0xFE;
    while (r > 0) {
        buf = buf == 0;
        StartFrame(0);
        ode = GetODE() ^ 1;
        src = (u8*)((ode * 0x500) + 0x80100000);
        rect.x = 0;
        rect.y = 0;
        rect.w = 0x280;
        rect.h = 1;
        rect.y = ode;
        while (rect.y < 0x1E0) {
            LoadImage(&rect, (u_long*)src);
            DrawSync(0);
            rect.y += 2;
            src += 0xA00;
        }

        ClearOTagR(&g_sceaTextOT[buf], LEN(g_sceaTextOT));
        SetTile(&g_sceaTextFadeTile[buf]);
        SetSemiTrans(&g_sceaTextFadeTile[buf], 1);
        (&g_sceaTextFadeTile[buf])->x0 = 0x1E;
        (&g_sceaTextFadeTile[buf])->y0 = 0xC8;
        (&g_sceaTextFadeTile[buf])->w = 0x244;
        (&g_sceaTextFadeTile[buf])->h = 0x4A;
        (&g_sceaTextFadeTile[buf])->r0 = r;
        (&g_sceaTextFadeTile[buf])->g0 = g;
        (&g_sceaTextFadeTile[buf])->b0 = b;
        AddPrim(&g_sceaTextOT[buf], &g_sceaTextFadeTile[buf]);
        tp = GetTPage(2, 2, 0, 0);
        SetDrawMode(&g_sceaTextDrMode[buf], 1, 1, tp, NULL);
        AddPrim(&g_sceaTextOT[buf], &g_sceaTextDrMode[buf]);
        DrawOTag(&g_sceaTextOT[buf]);
        r -= 2;
        g -= 2;
        b -= 2;
    }

    for (i = 0; i < 300; i++) {
        buf = buf == 0;
        StartFrame(0);
        ode = GetODE() ^ 1;
        src = (u8*)((ode * 0x500) + 0x80100000);
        rect.x = 0;
        rect.y = 0;
        rect.w = 0x280;
        rect.h = 1;
        rect.y = ode;
        while (rect.y < 0x1E0) {
            LoadImage(&rect, (u_long*)src);
            DrawSync(0);
            rect.y += 2;
            src += 0xA00;
        }
    }

    while (r < 0xFE) {
        buf = buf == 0;
        StartFrame(0);
        ode = GetODE() ^ 1;
        src = (u8*)((ode * 0x500) + 0x80100000);
        rect.x = 0;
        rect.y = 0;
        rect.w = 0x280;
        rect.h = 1;
        rect.y = ode;
        while (rect.y < 0x1E0) {
            LoadImage(&rect, (u_long*)src);
            DrawSync(0);
            rect.y += 2;
            src += 0xA00;
        }

        ClearOTagR(&g_sceaTextOT[buf], LEN(g_sceaTextOT));
        SetTile(&g_sceaTextFadeTile[buf]);
        SetSemiTrans(&g_sceaTextFadeTile[buf], 1);
        (&g_sceaTextFadeTile[buf])->x0 = 0x1E;
        (&g_sceaTextFadeTile[buf])->y0 = 0xC8;
        (&g_sceaTextFadeTile[buf])->w = 0x244;
        (&g_sceaTextFadeTile[buf])->h = 0x4A;
        (&g_sceaTextFadeTile[buf])->r0 = r;
        (&g_sceaTextFadeTile[buf])->g0 = g;
        (&g_sceaTextFadeTile[buf])->b0 = b;
        AddPrim(&g_sceaTextOT[buf], &g_sceaTextFadeTile[buf]);
        tp = GetTPage(2, 2, 0, 0);
        SetDrawMode(&g_sceaTextDrMode[buf], 1, 1, tp, NULL);
        AddPrim(&g_sceaTextOT[buf], &g_sceaTextDrMode[buf]);
        DrawOTag(&g_sceaTextOT[buf]);
        r += 2;
        g += 2;
        b += 2;
    }

    SetDispMask(0);
}

void ENDING_Loop(s32 isEndCredits) {
    u8 unused[0x100];
    RECT rect;
    s16 col;
    TILE* tile;
    s32 h = 0x1E0;

    while (1) {
        SetGameResolution(320, 240, 0x200, 0, 0, 0);
        if (isEndCredits) {
            rect.x = 0;
            rect.y = 0;
            rect.w = 960;
            rect.h = h;
        } else {
            rect.x = 0;
            rect.y = 0;
            rect.w = h;
            rect.h = h;
        }
        ClearImage(&rect, 0, 0, 0);
        while (DrawSync(1)) {
        }
        EndingInitNodes();
        g_endingVSyncMode = 0;
        g_endingNextPrim = (void*)0x801F0000;
        if (isEndCredits) {
            EndingInitScriptPc(script_ending_credits);
        } else {
            EndingInitScriptPc(script_intro_credits);
        }
        g_endingInProgress = 1;
        while (g_endingInProgress) {
            VSync(1);
            DrawSync(0);
            VSync(1);
            g_endingDbIndex = StartFrame(g_endingVSyncMode);
            if (g_endingDbIndex != 0) {
                g_endingNextPrim = (void*)0x801F0000;
            }
            rect.x = D_8007EBD0->clip.x;
            rect.y = D_8007EBD0->clip.y;
            if (D_8007EBD8->isrgb24 == 0) {
                rect.w = D_8007EBD0->clip.w;
            } else {
                rect.w = D_8007EBD0->clip.w * 3 / 2;
            }
            rect.h = D_8007EBD0->clip.h;
            ClearImage(&rect, 0, 0, 0);
            DrawSync(0);
            VSync(1);
            if (SystemCdromReadChain() == 10) {
                func_800354CC();
            }
            ClearOTagR(&g_endingOT[g_endingDbIndex], 1);
            g_endingCurOT = &g_endingOT[g_endingDbIndex];
            EndingExecuteScript();
            EndingRunNodes();
            DrawOTag(&g_endingOT[g_endingDbIndex]);
            VSync(1);
            if (!isEndCredits) {
                if (g_endingPad0KeysPressed &
                    (PAD_START | PAD_SELECT | PAD_TRIANGLE | PAD_CIRCLE | PAD_CROSS | PAD_SQUARE)) {
                    goto fade_out;
                }
            }
        }
    }

fade_out:
    g_AkaoCmd.opcode = AKAO_VOL_SLIDE_FROM_CURR;
    g_AkaoCmd.params[0] = 0x3C;
    g_AkaoCmd.params[1] = 0;
    AkaoExec();
    for (col = 0; col < 0xFF; col += 4) {
        g_endingDbIndex = StartFrame(g_endingVSyncMode);
        rect.x = D_8007EBD0->clip.x;
        rect.y = D_8007EBD0->clip.y;
        rect.w = D_8007EBD0->clip.w;
        rect.h = D_8007EBD0->clip.h;
        ClearImage(&rect, 0, 0, 0);
        DrawSync(0);
        if (SystemCdromReadChain() == 10) {
            func_800354CC();
        }
        ClearOTagR(&g_endingOT[g_endingDbIndex], 1);
        g_endingCurOT = &g_endingOT[g_endingDbIndex];
        EndingRunNodes();
        DrawOTag(&g_endingOT[g_endingDbIndex]);
        ClearOTagR(&g_endingFadeOutOT[g_endingDbIndex], 1);
        SetTile(&g_endingFadeOutTile[g_endingDbIndex]);
        SetSemiTrans(&g_endingFadeOutTile[g_endingDbIndex], 1);
        setRGB0(&g_endingFadeOutTile[g_endingDbIndex], col, col, col);
        tile = &g_endingFadeOutTile[g_endingDbIndex];
        setXY0(tile, 0, 0);
        setWH(tile, 320, 240);
        AddPrim(&g_endingFadeOutOT[g_endingDbIndex], tile);
        SetDrawMode(&g_endingFadeOutDrMode[g_endingDbIndex], 0, 0, GetTPage(2, 2, 0, 0), NULL);
        AddPrim(&g_endingFadeOutOT[g_endingDbIndex], &g_endingFadeOutDrMode[g_endingDbIndex]);
        DrawOTag(&g_endingFadeOutOT[g_endingDbIndex]);
    }
    VSync(4);
    ResetGraph(1);
}

