func makeObjdiffConfig(b BuildConfig) objdiffConfig {
	var units []objdiffUnit
	var categories []objdiffProgressCategory
	kindCount := map[string]int{}
	for _, o := range b.Overlays {
		meta, ok := metaOverlays[o.Name]
		if !ok {
			panic(fmt.Sprintf("no metaOverlay entry for overlay %q", o.Name))
		}
		kindCount[meta.kind]++
	}
	seenKind := map[string]bool{}
	for _, o := range b.Overlays {
		meta := metaOverlays[o.Name]
		kindName, ok := metaCategories[meta.kind]
		if !ok {
			panic(fmt.Sprintf("no metaCategories entry for kind %q", meta.kind))
		}
		categoryID := meta.kind
		categoryName := kindName
		if kindCount[meta.kind] > 1 {
			categoryID = fmt.Sprintf("%s.%s", meta.kind, meta.id)
			categoryName = meta.name
			if !seenKind[meta.kind] {
				seenKind[meta.kind] = true
				categories = append(categories, objdiffProgressCategory{
					ID:   meta.kind,
					Name: kindName,
				})
			}
		}
		srcDir := filepath.Join(b.SrcPath, o.BasePath)
		asmDir := filepath.Join(b.AsmPath, o.BasePath)
		categories = append(categories, objdiffProgressCategory{
			ID:   categoryID,
			Name: categoryName,
		})
		for _, src := range o.Segments {
			if len(src) < 2 {
				continue
			}
			cat, ok := src[1].(string)
			if !ok {
				continue
			}
			name := ""
			if len(src) >= 3 {
				name = segmentName(src[2])
			}
			if name == "" {
				if v, ok := src[0].(uint64); ok {
					name = strconv.FormatInt(int64(v), 16)
					name = strings.ToUpper(name)
				}
			}
			if name == "" {
				panic("bug")
			}
			switch cat {
			case "c":
				srcFile := filepath.Join(srcDir, name+".c")
				objFile := filepath.Join(b.BuildPath, srcFile+".o")
				units = append(units, objdiffUnit{
					Name:       fmt.Sprintf("%s/%s", o.Name, name),
					BasePath:   objFile,
					TargetPath: targetPath(objFile),
					Metadata: objdiffMetadata{
						SourcePath:         srcFile,
						ProgressCategories: unitCategories(meta.kind, categoryID),
					},
				})
			case "hasm":
				srcFile := filepath.Join(srcDir, name+".s")
				objFile := filepath.Join(b.BuildPath, srcFile+".o")
				units = append(units, objdiffUnit{
					Name:       fmt.Sprintf("%s/%s", o.Name, name),
					BasePath:   objFile,
					TargetPath: targetPath(objFile),
					Metadata: objdiffMetadata{
						SourcePath:         srcFile,
						ProgressCategories: unitCategories(meta.kind, categoryID),
					},
				})
			case "data":
				fallthrough
			case "sbss":
				fallthrough
			case "bss":
				asmFile := filepath.Join(asmDir, "data", fmt.Sprintf("%s.%s.s", name, cat))
				objFile := filepath.Join(b.BuildPath, asmFile+".o")
				units = append(units, objdiffUnit{
					Name:       fmt.Sprintf("%s/%s_%s", o.Name, name, cat),
					BasePath:   objFile,
					TargetPath: targetPath(objFile),
					Metadata: objdiffMetadata{
						SourcePath:         asmFile,
						ProgressCategories: unitCategories(meta.kind, categoryID),
					},
				})
			}
		}
	}
	return objdiffConfig{
		CustomMake:  "ninja",
		BaseDir:     b.BuildPath,
		BuildBase:   true,
		TargetDir:   targetPath(b.BuildPath),
		BuildTarget: false,
		WatchPatterns: []string{
			"include/**.h",
			"src/**.c",
			"src/**.h",
			"src/**.s",
		},
		IgnorePatterns: []string{
			"build/**/*",
		},
		Units:            units,
		ProgressCategory: categories,
	}
}

func writeObjdiffConfig(b BuildConfig) error {
	data, err := json.Marshal(makeObjdiffConfig(b))
	if err != nil {
		return err
	}
	return os.WriteFile("objdiff.json", data, 0644)
}

func targetPath(path string) string {
	path = strings.Replace(path, "report/", "", 1)
	return filepath.Join("expected", path)
}

func unitCategories(kind, categoryID string) []string {
	if kind == categoryID {
		return []string{kind}
	}
	return []string{kind, categoryID}
}
